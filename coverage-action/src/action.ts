import type { CoverageReport, LineRange } from "./cobertura";
import * as core from "@actions/core";
import * as github from "@actions/github";
import { escapeMarkdown } from "./utils";
import { processCoverage } from "./cobertura";
import {
  actionPayloadSchema,
  booleanInputSchema,
  integerInputSchema,
  minimumCoverageInputSchema,
  pullRequestNumberInputSchema,
} from "./schemas";
import type { ActionPayload } from "./schemas";

interface PullRequestInfo {
  pullRequestNumber: number | undefined;
  commit: string | null;
}
export interface ReportOptions {
  minimumCoverage?: number;
  reportTitle?: string;
  skipCovered?: boolean;
  showLine?: boolean;
  showBranch?: boolean;
  showPackage?: boolean;
  showClassNames?: boolean;
  showMissing?: boolean;
  showMissingMaxLength?: number;
  linkMissingLines?: boolean;
  linkMissingLinesSourceDir?: string | null;
  filteredFiles?: string[] | null;
}

declare const __COVERAGE_ACTION_VERSION__: string;

const client = github.getOctokit(
  core.getInput("repo_token", { required: true }),
);
const credits = "Generated by 🐐";
const actionLink = "[goatwu1993/actions/coverage-action](https://github.com/goatwu1993/actions/tree/main/coverage-action)";

function parseBoolean(value: string): boolean {
  return booleanInputSchema.parse(value);
}

async function action(payload: unknown = {}): Promise<void> {
  const { pullRequestNumber, commit } = await pullRequestInfo(actionPayloadSchema.parse(payload));
  if (!commit) {
    core.error("Found no commit.");
    return;
  }

  const path = core.getInput("path", { required: true });
  const skipCovered = parseBoolean(
    core.getInput("skip_covered", { required: true }),
  );
  const showLine = parseBoolean(core.getInput("show_line", { required: true }));
  const showBranch = parseBoolean(
    core.getInput("show_branch", { required: true }),
  );
  const minimumCoverage = minimumCoverageInputSchema.parse(
    core.getInput("minimum_coverage", { required: true }),
  );
  const failBelowThreshold = parseBoolean(
    core.getInput("fail_below_threshold", { required: false }) || "false",
  );
  const showClassNames = parseBoolean(
    core.getInput("show_class_names", { required: true }),
  );
  const showMissing = parseBoolean(
    core.getInput("show_missing", { required: true }),
  );
  const showMissingMaxLengthInput = core.getInput("show_missing_max_length", {
    required: false,
  });
  const showMissingMaxLength = showMissingMaxLengthInput
    ? integerInputSchema.parse(showMissingMaxLengthInput)
    : -1;
  const linkMissingLines = parseBoolean(
    core.getInput("link_missing_lines", { required: false }) || "false",
  );
  const linkMissingLinesSourceDir =
    core.getInput("link_missing_lines_source_dir", { required: false }) || null;
  const onlyChangedFiles = parseBoolean(
    core.getInput("only_changed_files", { required: true }),
  );
  const reportName = core.getInput("report_name", { required: false });
  const reportTitle = core.getInput("report_title", { required: false });

  const changedFiles = onlyChangedFiles
    ? await listChangedFiles(requirePullRequestNumber(pullRequestNumber))
    : null;

  const manifest = await processCoverage(path);
  const comment = markdownReport(manifest, commit, {
    minimumCoverage,
    reportTitle,
    skipCovered,
    showLine,
    showBranch,
    showPackage: parseBoolean(
      core.getInput("show_package", { required: false }) || "true",
    ),
    showClassNames,
    showMissing,
    showMissingMaxLength,
    linkMissingLines,
    linkMissingLinesSourceDir,
    filteredFiles: changedFiles,
  });

  const belowThreshold = manifest.some(
    (report) => Math.floor(report.total) < minimumCoverage,
  );

  if (pullRequestNumber) {
    await addComment(pullRequestNumber, comment, reportName);
  }
  await addCheck(
    comment,
    reportName,
    commit,
    failBelowThreshold ? (belowThreshold ? "failure" : "success") : "neutral",
  );

  if (failBelowThreshold && belowThreshold) {
    core.setFailed("Minimum coverage requirement was not satisfied");
  }
}

function requirePullRequestNumber(pullRequestNumber: number | undefined): number {
  if (pullRequestNumber === undefined) {
    throw new Error("only_changed_files requires a pull request.");
  }
  return pullRequestNumber;
}

function formatFileUrl(sourceDir: string | null, fileName: string, commit: string) {
  const repo = github.context.repo;
  sourceDir = sourceDir ? sourceDir : "";
  // Strip leading and trailing slashes.
  sourceDir = sourceDir.replace(/\/$/, "").replace(/^\//, "");
  const path = (sourceDir ? `${sourceDir}/` : "") + fileName;
  const githubUrl = process.env["GITHUB_SERVER_URL"] || "https://github.com";
  return `${githubUrl}/${repo.owner}/${repo.repo}/blob/${commit}/${path}`;
}

function formatRangeText({ start, end }: LineRange) {
  return `${start}` + (start === end ? "" : `-${end}`);
}

function tickWrap(string: string) {
  return "`" + string + "`";
}

function cropRangeList(separator: string, showMissingMaxLength: number, ranges: string[]): [string[], boolean] {
  if (showMissingMaxLength <= 0) return [ranges, false];
  let accumulatedJoin = "";
  for (const [index, range] of ranges.entries()) {
    accumulatedJoin += `${separator}${range}`;
    if (index === 0) continue;
    if (accumulatedJoin.length > showMissingMaxLength)
      return [ranges.slice(0, index), true];
  }
  return [ranges, false];
}

function linkRange(fileUrl: string, range: string) {
  const [start, end] = range.slice(1, -1).split("-", 2);
  const rangeReference = `L${start}` + (end ? `-L${end}` : "");
  // Insert plain=1 to disabled rendered views.
  const url = `${fileUrl}?plain=1#${rangeReference}`;
  return `[${range}](${url})`;
}

function formatMissingLines(
  fileUrl: string,
  lineRanges: LineRange[],
  showMissingMaxLength: number,
  showMissingLineLinks: boolean,
) {
  const formatted = lineRanges.map(formatRangeText);
  const separator = " ";
  // Apply cropping before inserting ticks and linking, so that only non-syntax
  // characters are counted.
  const [cropped, isCropped] = cropRangeList(
    separator,
    showMissingMaxLength,
    formatted,
  );
  const wrapped = cropped.map(tickWrap);
  const linked = showMissingLineLinks
    ? wrapped.map((range) => linkRange(fileUrl, range))
    : wrapped;
  const joined = linked.join(separator) + (isCropped ? " &hellip;" : "");
  return joined || " ";
}

function markdownReport(reports: readonly CoverageReport[], commit: string, options: ReportOptions = {}): string {
  const {
    minimumCoverage = 100,
    reportTitle = "",
    skipCovered = true,
    showLine = false,
    showBranch = false,
    showPackage = true,
    showClassNames = false,
    showMissing = false,
    showMissingMaxLength = -1,
    linkMissingLines = false,
    linkMissingLinesSourceDir = null,
    filteredFiles = null,
  } = options;
  const title = reportTitle || "Coverage Report";
  const status = (total: number) =>
    total >= minimumCoverage ? ":white_check_mark:" : ":x:";
  // Setup files
  const files: (string | undefined)[][] = [];
  let output = "";
  for (const report of reports) {
    const folder = reports.length <= 1 ? "" : ` ${report.folder}`;
    for (const file of report.files.filter(
      (file) =>
        (!skipCovered || file.total < 100) &&
        (filteredFiles == null || filteredFiles.includes(file.filename)),
    )) {
      const fileTotal = Math.floor(file.total);
      const fileLines = Math.floor(file.line);
      const fileBranch = Math.floor(file.branch);
      files.push([
        escapeMarkdown(showClassNames ? file.name : file.filename),
        `\`${fileTotal}%\``,
        showLine ? `\`${fileLines}%\`` : undefined,
        showBranch ? `\`${fileBranch}%\`` : undefined,
        status(fileTotal),
        showMissing
          ? formatMissingLines(
              formatFileUrl(linkMissingLinesSourceDir, file.filename, commit),
              file.missing,
              showMissingMaxLength,
              linkMissingLines,
            )
          : undefined,
      ]);
    }

    // Construct table
    /*
    | File          | Coverage |                    |
    |---------------|:--------:|:------------------:|
    | **All files** | `78%`    | :x:                |
    | foo.py        | `80%`    | :white_check_mark: |
    | bar.py        | `75%`    | :x:                |

    _Minimum allowed coverage is `80%`_
    */

    const total = Math.floor(report.total);
    const linesTotal = Math.floor(report.line);
    const branchTotal = Math.floor(report.branch);
    const packages = showPackage
      ? (report.packages ?? []).map((packageReport) => {
          const packageTotal = Math.floor(packageReport.total);
          return [
            `**Package: ${escapeMarkdown(packageReport.name)}**`,
            `\`${packageTotal}%\``,
            showLine ? `\`${Math.floor(packageReport.line)}%\`` : undefined,
            showBranch ? `\`${Math.floor(packageReport.branch)}%\`` : undefined,
            status(packageTotal),
            showMissing ? " " : undefined,
          ];
        })
      : [];
    const table = [
      [
        "File",
        "Coverage",
        showLine ? "Lines" : undefined,
        showBranch ? "Branches" : undefined,
        " ",
        showMissing ? "Missing" : undefined,
      ],
      [
        "-",
        ":-:",
        showLine ? ":-:" : undefined,
        showBranch ? ":-:" : undefined,
        ":-:",
        showMissing ? ":-:" : undefined,
      ],
      [
        "**All files**",
        `\`${total}%\``,
        showLine ? `\`${linesTotal}%\`` : undefined,
        showBranch ? `\`${branchTotal}%\`` : undefined,
        status(total),
        showMissing ? " " : undefined,
      ],
      ...packages,
      ...files,
    ]
      .map((row) => {
        return `| ${row.filter(Boolean).join(" | ")} |`;
      })
      .join("\n");
    const titleText = `## ${escapeMarkdown(title + folder)}`;
    output += `${titleText}\n\n${table}\n\n`;
  }
  const minimumCoverageText = `_Minimum allowed coverage is \`${minimumCoverage}%\`_`;
  const footerText = `> ${credits} ${actionLink} v${__COVERAGE_ACTION_VERSION__} against ${commit}`;
  output += `${minimumCoverageText}\n\n${footerText}`;
  return output;
}

async function addComment(pullRequestNumber: number, body: string, reportName?: string) {
  const comments = await client.rest.issues.listComments({
    issue_number: pullRequestNumber,
    ...github.context.repo,
  });
  const commentFilter = reportName ? reportName : credits;
  const comment = comments.data.find((comment) =>
    comment.body?.includes(commentFilter),
  );
  if (comment != null) {
    await client.rest.issues.updateComment({
      comment_id: comment.id,
      body: body,
      ...github.context.repo,
    });
  } else {
    await client.rest.issues.createComment({
      issue_number: pullRequestNumber,
      body: body,
      ...github.context.repo,
    });
  }
}

async function addCheck(body: string, reportName: string, sha: string, conclusion: "success" | "failure" | "neutral") {
  const checkName = reportName ? reportName : "coverage";

  await client.rest.checks.create({
    name: checkName,
    head_sha: sha,
    status: "completed",
    conclusion: conclusion,
    output: {
      title: checkName,
      summary: body,
    },
    ...github.context.repo,
  });
}

async function listChangedFiles(pullRequestNumber: number) {
  const files = await client.rest.pulls.listFiles({
    pull_number: pullRequestNumber,
    ...github.context.repo,
  });
  return files.data.map((file) => file.filename);
}

async function pullRequestInfo(payload: ActionPayload = {}): Promise<PullRequestInfo> {
  let commit: string | null = null;
  const suppliedPullRequestNumber = core.getInput("pull_request_number", {
    required: false,
  });

  let pullRequestNumber: number | undefined;
  if (suppliedPullRequestNumber) {
    // Use the supplied PR
    pullRequestNumber = pullRequestNumberInputSchema.parse(suppliedPullRequestNumber);
    const { data } = await client.rest.pulls.get({
      pull_number: pullRequestNumber,
      ...github.context.repo,
    });
    commit = data.head.sha;
  } else if (payload.workflow_run) {
    // Fetch all open PRs and match the commit hash.
    commit = payload.workflow_run.head_commit?.id ?? null;
    const { data } = await client.rest.pulls.list({
      ...github.context.repo,
      state: "open",
    });
    pullRequestNumber = data.filter((d) => d.head.sha === commit).at(-1)?.number;
  } else if (payload.pull_request) {
    // Try to find the PR from payload
    const { pull_request: pullRequest } = payload;
    pullRequestNumber = pullRequest.number;
    commit = pullRequest.head.sha;
  } else if (payload.after) {
    commit = payload.after;
  }

  return { pullRequestNumber, commit };
}

export {
  action,
  markdownReport,
  addComment,
  addCheck,
  listChangedFiles,
};
